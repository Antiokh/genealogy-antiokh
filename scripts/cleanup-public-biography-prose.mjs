async function markdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await markdownFiles(full));
    else if (entry.isFile() && /\.mdx?$/i.test(entry.name)) files.push(full);
  }
  return files;
}

let changed = 0;
let placeholdersRemoved = 0;
let patronymicNotesRemoved = 0;

for (const file of await markdownFiles(ROOT)) {
  const raw = await readFile(file, 'utf8');
  if (!raw.startsWith('---\n')) continue;
  const end = raw.indexOf('\n---\n', 4);
  if (end < 0) continue;
  const frontmatter = raw.slice(4, end);
  if (!/(?:^|\n)entity:\s*["']?person["']?\s*(?:\n|$)/i.test(frontmatter)) continue;

  const offset = end + 5;
  let body = raw.slice(offset);
  let next = raw;

  if (PLACEHOLDER.test(body)) {
    next = raw.slice(0, offset);
    placeholdersRemoved += 1;
  } else {
    for (const [from, to] of replacements.get(file) ?? []) {
      if (body.includes(from)) body = body.replace(from, to);
    }

    const beforePatronymic = body;
    body = body.replace(/\n*Отчество восстановлено по [^\n]*\.?\n?/gu, '\n');
    if (body !== beforePatronymic) patronymicNotesRemoved += 1;

    body = body.replace(/\n{3,}/g, '\n\n');
    next = raw.slice(0, offset) + body;
  }

  if (next !== raw) {
    await writeFile(file, next, 'utf8');
    changed += 1;
  }
}

console.log(`Updated ${changed} person files.`);
console.log(`Removed ${placeholdersRemoved} placeholder biographies.`);
console.log(`Removed patronymic reconstruction notes from ${patronymicNotesRemoved} biographies.`);
